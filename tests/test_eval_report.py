from __future__ import annotations

import re

import yaml

from evals.report import NOTES, note_for, render


def _results(**overrides: object) -> dict:
    sections = [
        {
            "id": "exceptions",
            "title": "Exception recall",
            "target": "≥ 95%",
            "value": "100%",
            "status": "pass",
            "source": "run",
            "details": {},
            "misses": [
                {"id": "exceptions:unexplained:V006:SO1|1", "what": "lot shipped after expiry"},
                {"id": "exceptions:unexplained:V006:SO2|1", "what": "lot shipped after expiry"},
            ],
        },
        {
            "id": "agent",
            "title": "Agent",
            "target": "≥ 85%",
            "value": "82%",
            "status": "fail",
            "source": "saved agent_x.json",
            "details": {},
            "misses": [{"id": "agent:V099_new_pattern", "what": "odd"}],
        },
        {
            "id": "onboarding",
            "title": "Onboarding",
            "target": "report",
            "value": "8 s",
            "status": "report",
            "source": "run",
            "details": {"note": "automated"},
            "misses": [],
        },
    ]
    return {
        "generated_at": "2026-09-16T00:00:00+00:00",
        "commit": "abc1234",
        "database": "db",
        "sections": sections,
        **overrides,
    }


def test_report_summarises_every_section_and_counts_statuses() -> None:
    text = render(_results(), notes=[])
    assert "Generated by `evals/run_evals.py`" in text and "`abc1234`" in text
    assert "| Agent | ≥ 85% | 82% | FAIL | saved agent_x.json |" in text
    assert "**1 pass, 1 fail, 1 reported, 0 skipped.**" in text and "Failing: Agent." in text


def test_a_miss_without_a_note_is_shown_as_not_yet_analysed_never_dropped() -> None:
    notes = [{"match": "^exceptions:unexplained:V006:", "why": "genuine expired lots", "changed": "nothing"}]
    text = render(_results(), notes=notes)
    assert (
        "| `exceptions:unexplained:V006:SO1\\|1 (+1 alike)` | 2 misses, e.g. lot shipped after expiry | "
        "genuine expired lots | nothing |" in text
    )
    assert "| `agent:V099_new_pattern` | odd | not yet analysed | not yet analysed |" in text
    assert "3 misses; 1 not yet analysed." in text


def test_every_repo_failure_note_is_well_formed_and_matches_by_regex() -> None:
    notes = yaml.safe_load(NOTES.read_text(encoding="utf-8"))["notes"]
    for n in notes:
        assert set(n) == {"match", "why", "changed"} and n["why"] and n["changed"]
        re.compile(n["match"])
    assert note_for("answers:Q060", notes) is not None
    assert note_for("answers:Q999", notes) is None
